from decimal import Decimal, ROUND_HALF_UP
from html import escape


def _money(value):
    return f"{Decimal(str(value)).quantize(Decimal('0.01'), rounding=ROUND_HALF_UP):,.2f}"


def _business(store):
    return {
        "name": store.setting("business_name", "Your Business").strip() or "Your Business",
        "tagline": store.setting("business_tagline", ""),
        "address": store.setting("business_address", ""),
        "phone": store.setting("business_phone", ""),
        "email": store.setting("business_email", ""),
        "tax_id": store.setting("business_tax_id", ""),
        "currency": store.setting("business_currency", "KES - Kenyan Shilling").split(" - ", 1)[0],
    }


def _frame(store, title, meta, rows, totals, note="", extra=""):
    business=_business(store)
    identity="<br>".join(escape(x) for x in (business["address"],business["phone"],business["email"],("Tax ID: "+business["tax_id"]) if business["tax_id"] else "") if x)
    table_rows="".join(
        "<tr><td>"+escape(str(r[0]))+"</td><td class='num'>"+escape(str(r[1]))+"</td><td class='num'>"+escape(str(r[2]))+"</td><td class='num'>"+escape(str(r[3]))+"</td><td class='num'>"+escape(str(r[4]))+"</td></tr>"
        for r in rows
    )
    total_rows="".join("<tr><th colspan='4'>"+escape(str(label))+"</th><th class='num'>"+escape(str(value))+"</th></tr>" for label,value in totals)
    metadata="".join("<div><b>"+escape(str(label))+":</b> "+escape(str(value or "—"))+"</div>" for label,value in meta)
    return f"""<!doctype html><html><head><meta charset='utf-8'><style>
      body{{font-family:Arial,sans-serif;color:#202020;font-size:10pt;margin:18px}}
      .brand{{font-size:20pt;font-weight:bold;margin:0}}.tagline{{color:#555;margin:2px 0 8px}}
      .identity{{color:#444;font-size:9pt;line-height:1.45}}h2{{font-size:16pt;margin:16px 0 8px}}
      .metadata{{display:flex;flex-wrap:wrap;gap:8px 22px;margin:12px 0;padding:9px;background:#f1f1f1}}
      table{{width:100%;border-collapse:collapse;margin-top:12px}}td,th{{padding:7px 6px;border-bottom:1px solid #ccc;text-align:left}}
      thead th{{background:#e9e9e9}}.num{{text-align:right}}tfoot th{{border-top:2px solid #777}}
      .note{{font-size:9pt;color:#555;margin-top:16px}}.extra{{margin-top:16px}}.status{{font-weight:bold}}
      @media print{{body{{margin:10mm}}}}
      </style></head><body>
      <h1 class='brand'>{escape(business['name'])}</h1>
      <div class='tagline'>{escape(business['tagline'])}</div><div class='identity'>{identity}</div>
      <h2>{escape(title)}</h2><div class='metadata'>{metadata}</div>
      <table><thead><tr><th>SKU</th><th>Item</th><th class='num'>Quantity</th><th class='num'>Unit price</th><th class='num'>Line total</th></tr></thead>
      <tbody>{table_rows}</tbody><tfoot>{total_rows}</tfoot></table>
      <div class='extra'>{extra}</div><p class='note'>{escape(note)}</p>
      <p class='note'>Generated by NextGen ERP. Sales tax uses the administrator's configured fixed rate and is not jurisdiction-specific tax or fiscal compliance. Verify applicable rates and document rules before live use. This document is not a fiscal receipt.</p>
      </body></html>"""


def render_invoice(store, sale_id):
    sale=store.conn.execute("SELECT * FROM sales WHERE id=?",(int(sale_id),)).fetchone()
    if not sale:
        raise ValueError("The selected sale no longer exists.")
    rows=store.conn.execute("SELECT * FROM sale_lines WHERE sale_id=? ORDER BY id",(int(sale_id),)).fetchall()
    currency=_business(store)["currency"]
    items=[[r["sku"],r["description"],r["quantity"],f"{currency} {_money(r['unit_price'])}",f"{currency} {_money(Decimal(r['line_total'])+Decimal(r['tax_amount'] or '0.00'))}"] for r in rows]
    net=Decimal(sale["total"]); paid=Decimal(sale["paid_total"])
    totals=[("Subtotal",f"{currency} {_money(sale['subtotal'])}")]
    if Decimal(sale["tax_rate"]) > 0:
        totals.append((f"{sale['tax_label']} ({_money(sale['tax_rate'])}%)",f"{currency} {_money(sale['tax_total'])}"))
    totals.extend([("Total",f"{currency} {_money(net)}"),("Paid after returns",f"{currency} {_money(paid)}"),("Balance",f"{currency} {_money(net-paid)}")])
    returns=store.operations.sales_returns(sale_id)
    extra=""
    if returns:
        parts="".join("<li>"+escape(r["return_number"])+" · "+escape(r["reason"])+" · refund "+escape(currency)+" "+escape(_money(r["refund_amount"]))+"</li>" for r in returns)
        extra="<h3>Returns and refunds</h3><ul>"+parts+"</ul>"
    title="SALE INVOICE / PAYMENT RECEIPT"+(" · "+sale["status"].upper() if sale["status"]!="Completed" else "")
    meta=[("Invoice",sale["sale_number"]),("Customer",sale["customer_name"]),("Date",sale["created_at"]),("Status",sale["status"]),("Payment",sale["payment_status"])]
    return title,_frame(store,title,meta,items,totals,extra=extra)


def render_quote(store, quote_id):
    quote=store.conn.execute("SELECT * FROM quotes WHERE id=?",(int(quote_id),)).fetchone()
    if not quote:
        raise ValueError("The selected quotation no longer exists.")
    lines=store.operations.quote_lines(quote_id)
    currency=_business(store)["currency"]
    rows=[[r["sku"],r["description"],r["quantity"],f"{currency} {_money(r['unit_price'])}",f"{currency} {_money(Decimal(r['line_total'])+Decimal(r['tax_amount'] or '0.00'))}"] for r in lines]
    title="SALES QUOTATION"
    totals=[("Subtotal",f"{currency} {_money(quote['subtotal'])}")]
    if Decimal(quote["tax_rate"]) > 0:
        totals.append((f"{quote['tax_label']} ({_money(quote['tax_rate'])}%)",f"{currency} {_money(quote['tax_total'])}"))
    totals.append(("Quotation total",f"{currency} {_money(quote['total'])}"))
    meta=[("Quotation",quote["quote_number"]),("Customer",quote["customer_name"]),("Created",quote["created_at"]),("Valid through",quote["expires_on"] or "Not specified"),("Status",quote["status"])]
    return title,_frame(store,title,meta,rows,totals,note="This quotation does not reserve inventory. Prices and availability may change until accepted and converted.")


def render_purchase_order(store, order_id):
    order=store.conn.execute("SELECT * FROM purchase_orders WHERE id=?",(int(order_id),)).fetchone()
    if not order:
        raise ValueError("The selected purchase order no longer exists.")
    currency=_business(store)["currency"]
    lines=store.operations.purchase_order_lines(order_id)
    rows=[]
    total=Decimal("0.00")
    for line in lines:
        amount=(Decimal(line["quantity"])*Decimal(line["unit_cost"])).quantize(Decimal("0.01"),rounding=ROUND_HALF_UP)
        total+=amount
        rows.append([line["sku"],line["description"],line["quantity"],f"{currency} {_money(line['unit_cost'])}",f"{currency} {_money(amount)}"])
    title="PURCHASE ORDER"
    meta=[("Order",order["order_number"]),("Supplier",order["supplier_name"]),("Created",order["created_at"]),("Status",order["status"])]
    received_total=sum((Decimal(r["paid_total"]) for r in store.operations.purchases() if r["order_id"]==int(order_id)),Decimal("0"))
    totals=[("Order value",f"{currency} {_money(total)}")]
    if received_total:
        totals.append(("Paid across receipts",f"{currency} {_money(received_total)}"))
    return title,_frame(store,title,meta,rows,totals,note="Goods received should be recorded in the ERP when physically delivered.")


def render_goods_received(store, purchase_id):
    purchase=store.conn.execute("SELECT * FROM purchases WHERE id=?",(int(purchase_id),)).fetchone()
    if not purchase:
        raise ValueError("The selected goods receipt no longer exists.")
    currency=_business(store)["currency"]
    lines=store.conn.execute("SELECT * FROM purchase_lines WHERE purchase_id=? ORDER BY id",(int(purchase_id),)).fetchall()
    rows=[[r["sku"],r["description"],r["quantity"],f"{currency} {_money(r['unit_cost'])}",f"{currency} {_money(r['line_total'])}"] for r in lines]
    title="GOODS RECEIVED NOTE"
    order=store.conn.execute("SELECT order_number FROM purchase_orders WHERE id=?",(purchase["order_id"],)).fetchone() if purchase["order_id"] else None
    meta=[("Receipt",purchase["purchase_number"]),("Purchase order",order["order_number"] if order else "Unplanned receipt"),("Supplier",purchase["supplier_name"]),("Date",purchase["created_at"]),("Status",purchase["status"])]
    totals=[("Received value",f"{currency} {_money(purchase['total'])}"),("Paid now",f"{currency} {_money(purchase['paid_total'])}")]
    return title,_frame(store,title,meta,rows,totals,note="Goods-received record generated from the quantities entered in the ERP.")


def render_repair_job(store, job_id):
    job=store.conn.execute("SELECT * FROM repair_jobs WHERE id=?",(int(job_id),)).fetchone()
    if not job:
        raise ValueError("The selected repair ticket no longer exists.")
    currency=_business(store)["currency"]
    parts=store.operations.repair_job_parts(job_id)
    rows=[[r["sku"],r["description"],r["quantity"],f"{currency} {_money(r['unit_price'])}",f"{currency} {_money(r['line_total'])}"] for r in parts]
    if not rows:
        rows=[["—","No parts issued", "—", "—", "—"]]
    subtotal=Decimal(job["subtotal"])
    if job["status"] not in {"Ready","Collected"}:
        subtotal=Decimal(job["labor_amount"])+sum((Decimal(r["line_total"]) for r in parts),Decimal("0.00"))
    parts_total=sum((Decimal(r["line_total"]) for r in parts),Decimal("0.00"))
    totals=[("Pre-tax estimate",f"{currency} {_money(job['estimate_amount'])}"),("Labor",f"{currency} {_money(job['labor_amount'])}"),("Parts",f"{currency} {_money(parts_total)}"),("Subtotal",f"{currency} {_money(subtotal)}")]
    if Decimal(job["tax_rate"])>0:
        totals.append((f"{job['tax_label']} ({_money(job['tax_rate'])}%)",f"{currency} {_money(job['tax_total'])}"))
    totals.extend([("Final total",f"{currency} {_money(job['total'])}"),("Paid",f"{currency} {_money(job['paid_total'])}"),("Balance",f"{currency} {_money(Decimal(job['total'])-Decimal(job['paid_total']))}")])
    events=store.operations.repair_job_events(job_id)
    event_html="<h3>Service history</h3><ul>"+"".join("<li>"+escape(e["created_at"]+" · "+e["event"]+" · "+e["details"]+" · "+e["actor"])+"</li>" for e in events)+"</ul>"
    meta=[("Ticket",job["ticket_number"]),("Customer",job["customer_name"]),("Device",job["device"]),("Serial number",job["serial_number"]),("Status",job["status"]),("Estimate approval",job["approval_status"]),("Technician",job["technician"]),("Received",job["created_at"]),("Reported fault",job["reported_fault"]),("Diagnosis",job["diagnosis"]),("Warranty / condition",job["warranty_notes"])]
    title="REPAIR JOB SHEET"
    return title,_frame(store,title,meta,rows,totals,note="Customer approval, parts usage, and collection status are recorded in the local repair history.",extra=event_html)
